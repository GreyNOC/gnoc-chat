#!/usr/bin/env python3
"""Rebuild Manual/MANUAL-INDEX.md - one row per T-NN rule across every manual volume.

WHY THIS EXISTS. The manual volumes are APPEND-ONLY by design (rotate, never truncate), and
CLAUDE.md used to @-import all of them, so every byte ever written was pasted into every
session until the set hit 584k against a 150k ceiling. An @-import of an append-only file is
structurally doomed. So: the INDEX is auto-loaded and REGENERATED; the VOLUMES are read on
demand and never truncated. Nothing is deleted, nothing is summarised away.

Regenerate after any manual edit:  scripts/doc-index.py
"""
import re, glob, os, datetime, sys

os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
RULE_CAP = 48    # per-rule CHARACTER clip for the restated Rule text; the volumes hold the full text
TITLE_CAP = 120  # per-rule CHARACTER clip for the HEADLINE
# WHY THE CAPS GOT TIGHTER (2026-10-27): this index is a POINTER layer - its own header says so, and
# tells the reader the full entry is one grep away. It had grown to 49.5k of a 150k auto-load budget
# that the whole set was exceeding at 123%, which means the instruction files were being SILENTLY
# TRUNCATED every session and nobody could know WHICH rules were in force. A deliberate uniform clip
# is strictly better than arbitrary truncation: every rule still gets its id and enough headline to
# recognise it, and `grep -A16 '^## T-58 ' Manual/GREYNOC-MANUAL*.md` still returns everything.

def clip(s, n):
    if len(s) <= n:
        return s
    cut = s[:n]
    for sep in ('. ', '; ', ', '):
        i = cut.rfind(sep)
        if i > n * 0.6:
            return cut[:i + 1].rstrip() + ' [...]'
    return cut.rsplit(' ', 1)[0] + ' [...]'

vols = [('Manual/GREYNOC-MANUAL.md', '01')]
for p in sorted(glob.glob('Manual/GREYNOC-MANUAL-0*.md')):
    if '.bak-' in p:
        continue
    vols.append((p, re.search(r'-(\d+)\.md$', p).group(1)))

rows = []
for path, tag in vols:
    txt = open(path).read()
    for m in re.finditer(r'^## (T-[0-9A-Za-z]+) (.+?)$(.*?)(?=^## |\Z)', txt, re.M | re.S):
        tid, title, body = m.group(1), m.group(2).strip(), m.group(3)
        r = re.search(r'\*\*Rule\.?\*\*(.*?)(?=\n\*\*|\n\n|\Z)', body, re.S)
        rule = ' '.join(r.group(1).split()) if r else '(no Rule field - fix the volume)'
        rows.append((tid, title, rule, tag))

if not rows:
    sys.exit('no T-NN entries parsed - refusing to write an empty index')

head = f"""# MANUAL INDEX - every technique rule, one line each

GENERATED by `scripts/doc-index.py`. Do NOT hand-edit: edit the volume, then regenerate.
Rebuilt {datetime.date.today()} from {len(vols)} volume(s), {len(rows)} rules.

This index IS auto-loaded every session. The manual VOLUMES are NOT, because they are
append-only and unbounded - that is the whole point of the split. Read a rule's **Why**,
**Receipt** and **Changed** history on demand, it is one grep away:

    grep -A16 '^## T-58 ' Manual/GREYNOC-MANUAL*.md

Volume 01 (`Manual/GREYNOC-MANUAL.md`) also permanently owns these sections, which are NOT
indexed here and must be grepped by heading before you hunt: `# §0 THE SCOREBOARD`,
THE ADMISSION TEST, the update protocol, `# §10 PER-PROGRAM INTEL` (read the row for your
target), `# §11 TOOLING AND ENVIRONMENT`, `# §12 CONDUCT`, `# §13 OPEN QUESTIONS`,
`# §14 RETIRED`. Later volumes hold only new or revised entries plus their changelog.

Precedence unchanged: SPINE.md over the Manual, the Manual over any older fragment, a NEWER
volume over an older one. This index is a pointer layer and never overrides a volume.

| id | what it says | vol |
|---|---|---|
"""

with open('Manual/MANUAL-INDEX.md', 'w') as f:
    f.write(head)
    for tid, title, rule, tag in rows:
        title = clip(title.replace('|', '/'), TITLE_CAP)
        rule = clip(rule.replace('|', '/'), RULE_CAP)
        f.write(f"| **{tid}** | **{title}.** {rule} | {tag} |\n")

n = os.path.getsize('Manual/MANUAL-INDEX.md')
print(f"{len(rows)} rules indexed -> Manual/MANUAL-INDEX.md  {n} bytes")

# Context-budget guard: the whole point of the split. Print it on every regeneration so a
# re-added @-import shows up here instead of as a truncation warning three sessions later.
LOADED = ['CLAUDE.md', 'SPINE.md', 'Manual/MANUAL-INDEX.md', 'Manual/HARNESS.md',
          'HANDOFF-CURRENT.md']
tot = sum(os.path.getsize(f) for f in LOADED if os.path.exists(f))
print(f"auto-loaded instruction set: {tot} chars = {tot/150000*100:.0f}% of the 150k ceiling")
for f in LOADED:
    if os.path.exists(f):
        print(f"    {os.path.getsize(f):>7}  {f}")
if tot > 150000:
    sys.exit("OVER THE CEILING - trim an index layer file, never re-import a volume")
